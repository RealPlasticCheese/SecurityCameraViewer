param(
    [ValidateSet('Configure', 'Stop', 'Uninstall')][string]$Action = 'Configure',
    [string]$InstallDirectory = $PSScriptRoot,
    [string]$DataDirectory = "$env:ProgramData\SecurityCameraViewer",
    [ValidateRange(1, 65535)][int]$Port = 5080,
    [ValidateSet('0.0.0.0', '127.0.0.1')][string]$BindAddress = '0.0.0.0',
    [ValidateSet('Service', 'Manual')][string]$Mode = 'Service',
    [switch]$OpenFirewall,
    [switch]$InstallFfmpeg,
    [string]$FfmpegPath,
    [switch]$Reconfigure,
    [ValidateSet('Preserve', 'Public', 'Dns', 'Internal')][string]$HttpsMode = 'Preserve',
    [string]$Hostname,
    [string]$DnsProvider
)
$ErrorActionPreference = 'Stop'
$serviceName = 'SecurityCameraViewer'
$firewallName = 'SecurityCameraViewer-HTTP'

function Invoke-Native {
    param([string]$File, [string[]]$Arguments)
    & $File @Arguments
    if ($LASTEXITCODE -ne 0) { throw "$File failed with exit code $LASTEXITCODE." }
}

function Stop-ViewerService {
    $service = Get-Service -Name $serviceName -ErrorAction SilentlyContinue
    if ($service) {
        Stop-Service -Name $serviceName
        $service.WaitForStatus('Stopped', [TimeSpan]::FromSeconds(45))
    }
}

function New-HostConfiguration {
    param([string]$Directory, [string]$Ffmpeg)
    return [ordered]@{
        urls = "http://${BindAddress}:$Port"
        settings = Join-Path $Directory 'data/settings.json'
        ffmpeg = $Ffmpeg
        'ai-model-directory' = Join-Path $Directory 'data/models'
    }
}

function Resolve-FfmpegExecutable {
    param([string]$Candidate, [string]$ChocolateyDirectory = $env:ChocolateyInstall)
    if (-not $Candidate) { return $null }
    if (-not $ChocolateyDirectory) { $ChocolateyDirectory = Join-Path $env:ProgramData 'chocolatey' }
    $shimDirectory = [IO.Path]::GetFullPath((Join-Path $ChocolateyDirectory 'bin')) + [IO.Path]::DirectorySeparatorChar
    if ([IO.Path]::GetFullPath($Candidate).StartsWith($shimDirectory, [StringComparison]::OrdinalIgnoreCase)) {
        $binaries = @(Get-ChildItem -LiteralPath (Join-Path $ChocolateyDirectory 'lib/ffmpeg') -Filter ffmpeg.exe -Recurse -ErrorAction SilentlyContinue)
        if ($binaries.Count -ne 1) { throw 'Cannot resolve the Chocolatey FFmpeg launcher. Pass -FfmpegPath pointing to the actual executable.' }
        return $binaries[0].FullName
    }
    return [IO.Path]::GetFullPath($Candidate)
}

function Set-ViewerService {
    param([string]$BinaryPath)
    if (-not (Get-Service -Name $serviceName -ErrorAction SilentlyContinue)) {
        New-Service -Name $serviceName -BinaryPathName $BinaryPath -StartupType Automatic -DisplayName 'Security Camera Viewer web server' | Out-Null
    }
    # Use the service API so paths containing spaces retain their embedded quotes
    # under both Windows PowerShell 5.1 and newer PowerShell versions.
    $service = Get-CimInstance -ClassName Win32_Service -Filter "Name='$serviceName'"
    $result = Invoke-CimMethod -InputObject $service -MethodName Change -Arguments @{
        PathName = $BinaryPath
        StartName = 'NT AUTHORITY\NetworkService'
        StartPassword = ''
        StartMode = 'Automatic'
    }
    if ($result.ReturnValue -ne 0) { throw "Could not configure Windows service: $($result.ReturnValue)." }
}

function New-CaddySite {
    if ($Hostname.Length -gt 253 -or $Hostname -notmatch '^(?=.{1,253}$)[a-zA-Z0-9](?:[a-zA-Z0-9.-]*[a-zA-Z0-9])?$' -or
        @($Hostname.Split('.') | Where-Object { $_ -notmatch '^[a-zA-Z0-9](?:[a-zA-Z0-9-]{0,61}[a-zA-Z0-9])?$' }).Count) {
        throw 'Enter a DNS hostname without a scheme, port, or path.'
    }
    if ($Port -in @(80, 443)) { throw 'The backend must use a port separate from the Caddy HTTP/HTTPS listeners.' }
    if ($HttpsMode -in @('Public', 'Dns') -and ($Hostname -notmatch '\.' -or $Hostname -match '\.(local|localhost|internal)$')) {
        throw 'Public certificates require a domain you control.'
    }
    $ipAddress = $null
    if ($HttpsMode -in @('Public', 'Dns') -and [Net.IPAddress]::TryParse($Hostname, [ref]$ipAddress)) {
        throw 'Public certificate setup requires a domain you control, not an IP address.'
    }
    $tls = ''
    if ($HttpsMode -eq 'Internal') { $tls = "    tls internal`n" }
    if ($HttpsMode -eq 'Dns') {
        if ($DnsProvider -notmatch '^[a-z][a-z0-9_]*$') { throw 'Enter the Caddy DNS provider module name.' }
        $credentials = if ($DnsProvider -eq 'cloudflare') { ' {env.CLOUDFLARE_API_TOKEN}' } else { '' }
        $tls = "    tls {`n        dns ${DnsProvider}${credentials}`n    }`n"
    }
    return "# Generated by SecurityCameraViewer setup; review before importing.`nhttps://${Hostname}:443 {`n${tls}    reverse_proxy 127.0.0.1:$Port`n}`n"
}

# Tests dot-source the functions without touching the host.
if ($MyInvocation.InvocationName -eq '.') { return }
if ($Action -eq 'Stop') { Stop-ViewerService; return }
if ($Action -eq 'Uninstall') {
    Stop-ViewerService
    if (Get-Service -Name $serviceName -ErrorAction SilentlyContinue) { Invoke-Native sc.exe @('delete', $serviceName) }
    Get-NetFirewallRule -Name $firewallName -ErrorAction SilentlyContinue | Remove-NetFirewallRule
    Write-Host 'Server removed. Settings, recordings, HTTPS configuration and certificates were retained.'
    return
}
Start-Transcript -Path (Join-Path $env:TEMP 'SecurityCameraViewer-setup.log') -Append | Out-Null

$InstallDirectory = [IO.Path]::GetFullPath($InstallDirectory)
$DataDirectory = [IO.Path]::GetFullPath($DataDirectory)
$executable = Join-Path $InstallDirectory 'SecurityCameraViewer.Web.exe'
if (-not (Test-Path -LiteralPath $executable)) { throw 'Published web server is missing.' }
$configFile = Join-Path $DataDirectory 'host.json'
$existing = if (Test-Path -LiteralPath $configFile) { Get-Content -LiteralPath $configFile -Raw | ConvertFrom-Json } else { $null }
if ($existing -and -not $Reconfigure) { $Port = ([Uri]$existing.urls).Port }
if ($HttpsMode -ne 'Preserve') { $site = New-CaddySite; $BindAddress = '127.0.0.1' }
$candidate = if ($FfmpegPath) { $FfmpegPath } elseif ($existing) { $existing.ffmpeg } else { (Get-Command ffmpeg.exe -ErrorAction SilentlyContinue).Source }
$ffmpeg = Resolve-FfmpegExecutable $candidate
if (-not $ffmpeg -or -not (Test-Path -LiteralPath $ffmpeg)) {
    if (-not $InstallFfmpeg) { throw 'FFmpeg is missing. Install it or select Install FFmpeg in setup.' }
    $winget = (Get-Command winget.exe -ErrorAction Stop).Source
    Invoke-Native $winget @('install', '--id', 'Gyan.FFmpeg', '--exact', '--source', 'winget', '--scope', 'machine', '--silent', '--accept-package-agreements', '--accept-source-agreements', '--disable-interactivity')
    $env:PATH = [Environment]::GetEnvironmentVariable('PATH', 'Machine') + ';' + [Environment]::GetEnvironmentVariable('PATH', 'User')
    $ffmpeg = Resolve-FfmpegExecutable (Get-Command ffmpeg.exe -ErrorAction SilentlyContinue).Source
    if (-not $ffmpeg) { throw 'FFmpeg was installed but could not be located. Add it to PATH and rerun setup.' }
}
Invoke-Native $ffmpeg @('-version')
New-Item -ItemType Directory -Path $DataDirectory -Force | Out-Null
# Machine configuration is administrator-owned; only application state is service-writable.
Invoke-Native icacls.exe @($DataDirectory, '/inheritance:r', '/grant:r', '*S-1-5-32-544:(OI)(CI)F', '*S-1-5-18:(OI)(CI)F', '*S-1-5-20:(OI)(CI)RX')
$stateDirectory = Join-Path $DataDirectory 'data'
New-Item -ItemType Directory -Path $stateDirectory -Force | Out-Null
Invoke-Native icacls.exe @($stateDirectory, '/grant:r', '*S-1-5-20:(OI)(CI)M')
if (-not $existing -or $Reconfigure) {
    if ($existing) { Copy-Item -LiteralPath $configFile -Destination "$configFile.pre-setup" }
    $config = New-HostConfiguration $DataDirectory $ffmpeg
    $temporary = "$configFile.new"
    $config | ConvertTo-Json | Set-Content -LiteralPath $temporary -Encoding UTF8
    Move-Item -LiteralPath $temporary -Destination $configFile -Force
} else {
    $Port = ([Uri]$existing.urls).Port
    if ($existing.ffmpeg -ne $ffmpeg) {
        $existing.ffmpeg = $ffmpeg
        $existing | ConvertTo-Json -Depth 100 | Set-Content -LiteralPath "$configFile.new" -Encoding UTF8
        Move-Item -LiteralPath "$configFile.new" -Destination $configFile -Force
    }
}
if ($Mode -eq 'Manual') {
    $currentUser = [Security.Principal.WindowsIdentity]::GetCurrent().User.Value
    Invoke-Native icacls.exe @($DataDirectory, '/grant', "*${currentUser}:(OI)(CI)M")
}
if ($HttpsMode -ne 'Preserve') {
    $siteFile = Join-Path $DataDirectory 'viewer.caddy.example'
    if (Test-Path -LiteralPath $siteFile) { throw 'HTTPS example already exists; review it before generating another.' }
    $site | Set-Content -LiteralPath $siteFile -Encoding UTF8
    Write-Host "HTTPS configuration generated: $siteFile. Follow INSTALL.md to configure Caddy and validate HTTPS."
}
Stop-ViewerService
if ($Mode -eq 'Service') {
    $binaryPath = '"' + $executable + '" --host-config "' + $configFile + '"'
    Set-ViewerService $binaryPath
    Invoke-Native sc.exe @('failure', $serviceName, 'reset=', '86400', 'actions=', 'restart/5000/restart/15000/restart/60000')
    if (-not [Diagnostics.EventLog]::SourceExists('SecurityCameraViewer.Web')) { New-EventLog -LogName Application -Source 'SecurityCameraViewer.Web' }
    Start-Service $serviceName
} else {
    if (Get-Service -Name $serviceName -ErrorAction SilentlyContinue) { Set-Service $serviceName -StartupType Disabled }
}
if ($OpenFirewall) {
    Get-NetFirewallRule -Name $firewallName -ErrorAction SilentlyContinue | Remove-NetFirewallRule
    New-NetFirewallRule -Name $firewallName -DisplayName 'Security Camera Viewer HTTP (private LAN)' -Direction Inbound -Action Allow -Protocol TCP -LocalPort $Port -Profile Private -RemoteAddress LocalSubnet | Out-Null
}
if ($Mode -eq 'Service') {
    $ready = $false
    for ($attempt = 0; $attempt -lt 30; $attempt++) {
        try {
            $response = Invoke-WebRequest "http://127.0.0.1:$Port/manifest.webmanifest" -UseBasicParsing -TimeoutSec 2
            if ($response.StatusCode -eq 200) { $ready = $true; break }
        } catch { Start-Sleep -Seconds 1 }
    }
    if (-not $ready) { throw 'Server failed its startup health check. Inspect the Windows application event log.' }
}
Write-Host "Installed. Open http://localhost:$Port/ and configure cameras in the browser."
