static void WriteDate(Span<byte> bytes, DateTime date)
{
    BinaryPrimitives.WriteUInt16LittleEndian(bytes, (ushort)date.Year);
    bytes[2] = (byte)date.Month; bytes[3] = (byte)date.Day; bytes[4] = (byte)date.Hour; bytes[5] = (byte)date.Minute; bytes[6] = (byte)date.Second;
}

static async Task<(ushort Type, ushort Subtype, byte[] Data)> ReadRequest(Stream stream, CancellationToken token)
{
    var header = new byte[16];
    await stream.ReadExactlyAsync(header, token);
    YsfCipher.Transform(header.AsSpan(2), true).CopyTo(header, 2);
    var payload = new byte[BinaryPrimitives.ReadUInt32LittleEndian(header.AsSpan(8))];
    await stream.ReadExactlyAsync(payload, token);
    return (BinaryPrimitives.ReadUInt16LittleEndian(header.AsSpan(4)), BinaryPrimitives.ReadUInt16LittleEndian(header.AsSpan(6)), YsfCipher.Transform(payload, true));
}

static async Task Reply(Stream stream, ushort type, ushort subtype, byte[] payload, CancellationToken token)
{
    var header = new byte[20];
    header[0] = 4; // Plain header, one extension word.
    BinaryPrimitives.WriteUInt16LittleEndian(header.AsSpan(4), type);
    BinaryPrimitives.WriteUInt16LittleEndian(header.AsSpan(6), subtype);
    BinaryPrimitives.WriteInt32LittleEndian(header.AsSpan(8), payload.Length);
    var bytes = header.Concat(payload).ToArray();
    for (var offset = 0; offset < bytes.Length; offset += 3)
    {
        await stream.WriteAsync(bytes.AsMemory(offset, Math.Min(3, bytes.Length - offset)), token);
    }
}

static async IAsyncEnumerable<NvrVideoFrame> TestFrames(byte[] data)
{
    await Task.Yield();
    yield return new(data, NvrVideoCodec.H264, true, 1_000_000, 320, 240);
    yield return new(data, NvrVideoCodec.H264, true, 3_000_000, 320, 240);
}

sealed class SlowNvrClient : INvrClient
{
    public bool Started { get; private set; }
    public Task<NvrDeviceInfo> GetDeviceInfoAsync(NvrConnection connection, CancellationToken token) => throw new NotSupportedException();
    public Task<IReadOnlyList<NvrRecording>> SearchAsync(NvrConnection connection, NvrRecordingRequest request, CancellationToken token) => throw new NotSupportedException();
    public async IAsyncEnumerable<NvrVideoFrame> ReadRecordingAsync(NvrConnection connection, NvrRecordingRequest request, [EnumeratorCancellation] CancellationToken token)
    {
        Started = true;
        await Task.Delay(Timeout.Infinite, token);
        yield break;
    }
}

